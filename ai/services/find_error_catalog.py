"""Каталог ошибок режима «В чём ошибка?» — единственный источник кодов.

Коды взяты из ``error.txt`` датасета «Одномерный массив»: 1–18 и 20–22
(кода 19 в каталоге нет). Каталог не хранится в БД: миграция не нужна,
подписи меняются вместе с кодом, а метки кейсов ссылаются на код числом.

Служебный суффикс ``build_eval_suffix()`` дописывает лаборатория промптов —
в production-промпт он НЕ входит: студент видит только человеческий разбор.
"""

from __future__ import annotations

# Код → короткая подпись для UI и служебной инструкции. Формулировки — по
# ``error.txt``, сокращённые до одной строки.
ERROR_CATALOG: dict[int, str] = {
    1: "неверное условие цикла: обрабатывается не n элементов",
    2: "массив объявлен с модификатором __in",
    3: "переменная не инициализирована перед использованием",
    4: "неверный размер в __bits (например, 1 бит вместо 8)",
    5: "в while нет изменения условия (i++) — бесконечный цикл",
    6: "цепочка else if вместо независимой проверки каждого элемента",
    7: "для выходной переменной использован += вместо =",
    8: "массиву присвоены начальные значения при объявлении",
    9: "неверный размер массива (не n байт)",
    10: "используется весь массив вместо отдельного элемента b[i]",
    11: "неверный оператор сравнения в if",
    12: "неверная реализация break",
    13: "выходная переменная обнулена — ответ всегда 0",
    14: "лишний if/else",
    15: "символьная константа вместо числовой",
    16: "имена переменных не совпадают с условием",
    17: "отсутствует модификатор __bits",
    18: "unsigned использован там, где нужен int",
    20: "переменные объявлены внутри main, а не глобально",
    21: "неверная формула/реализация результата",
    22: "в задаче отсутствует массив",
}

# Только эти коды допустимы в метках и в строке ``КОДЫ:``. Парсер и админка
# фильтруют по этому множеству; расширение каталога — правка таблицы выше.
VALID_ERROR_CODES: frozenset[int] = frozenset(ERROR_CATALOG)

# Метка «ошибок нет» в служебной строке.
NO_CODES_TOKEN = "—"


def build_eval_suffix() -> str:
    """Служебная инструкция лаборатории: просит последнюю строку ``КОДЫ: …``.

    Добавляется ТОЛЬКО в лаборатории промптов (после production-сообщения),
    чтобы метрики считались детерминированно. В промпт студента не входит.
    """
    catalog_lines = "\n".join(
        f"{code}. {ERROR_CATALOG[code]}" for code in sorted(ERROR_CATALOG)
    )
    return (
        "СЛУЖЕБНАЯ ИНСТРУКЦИЯ (только для автоматической проверки, "
        "студент её не увидит).\n"
        "В самом конце ответа добавь ровно одну строку с кодами найденных "
        "ошибок из каталога:\n"
        "КОДЫ: 3, 17\n"
        "Коды перечисляй через запятую, по возрастанию, без слова error_. "
        f"Если ошибок нет — напиши: КОДЫ: {NO_CODES_TOKEN}\n"
        "Строка КОДЫ должна быть последней строкой ответа и не заменяет "
        "человеческий разбор — сначала разбор, потом строка.\n"
        "Каталог кодов:\n"
        f"{catalog_lines}"
    )
