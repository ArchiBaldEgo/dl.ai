def reclassify_false_error_to_success(apps, schema_editor):
    from django.db import connection

    AIRequestLog = apps.get_model("ai", "AIRequestLog")
    table = AIRequestLog._meta.db_table

    # Оставляем только error_message='' (blank), непустой response_text и ни
    # одной фразы реальной ошибки. LOWER(response_text) LIKE '%<marker>%'
    # объединяем через OR внутри NOT (…). Маркеры — фиксированные литералы без
    # одиночных кавычек, но удваиваем кавычки на всякий случай.
    like_clauses = " OR ".join(
        f"LOWER(\"response_text\") LIKE '%{m.replace(chr(39), chr(39) * 2)}%'"
        for m in _KEEP_ERROR_MARKERS
    )

    sql = (
        f'UPDATE "{table}" '
        f"SET \"status\" = 'success' "
        f"WHERE \"status\" = 'error' "
        f"AND COALESCE(\"error_message\", '') = '' "
        f"AND \"response_text\" <> '' "
        f"AND NOT ({like_clauses})"
    )

    with connection.cursor() as cursor:
        cursor.execute(sql)


