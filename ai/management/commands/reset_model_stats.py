"""Разовый сброс накопленной статистики моделей (AIModelStats).

История: в duration батч-пар входили DL-поллинг/очередь записи и ожидание
семафора Ollama (429-бэкофф) — средние «≈N сек» в селекторе моделей разошлись
с реальной скоростью генерации (8 → 32 сек). Теперь duration меряет только
вызов модели; команда обнуляет накопленное, чтобы средние считались заново
по новым (честным) замерам пакетных прогонов.
"""
from django.core.management.base import BaseCommand

from ai.models import AIModelStats


class Command(BaseCommand):
    help = (
        "Сбросить накопленную статистику моделей (AIModelStats: среднее время "
        "и решённость из пакетных прогонов). Строки удаляются — статистика "
        "набирается заново следующими прогонами /arm/solve/ с флагом "
        "«заносить результаты в БД»."
    )

    def handle(self, *args, **options):
        deleted, _ = AIModelStats.objects.all().delete()
        self.stdout.write(self.style.SUCCESS(
            "AIModelStats сброшена: удалено %d строк. Средние «≈N сек» и "
            "%% решённых считаются заново по следующим пакетным прогонам." % deleted
        ))